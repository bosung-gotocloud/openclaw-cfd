def setup_snappy_hex_mesh_case(base_dir, base_name, h1, growth, layers, template_dir):
    """Copy template case and modify snappyHexMeshDict (port from tip-refine-snappy skill)."""
    case_dir = os.path.join(base_dir, f"{base_name}-case")
    if os.path.exists(case_dir):
        shutil.rmtree(case_dir)

    shutil.copytree(template_dir, case_dir)

    stl_dir = os.path.join(case_dir, "constant", "triSurface")
    if not os.path.exists(stl_dir):
        os.makedirs(stl_dir)

    dict_path = os.path.join(case_dir, "system", "snappyHexMeshDict")
    with open(dict_path, 'r') as f:
        content = f.read()

    # Replace surface name placeholders
    content = content.replace("\"BASENAME_surface.stl\"", f'"{base_name}_surface.stl"')
    content = content.replace("BASENAME_surface", f"{base_name}_surface")

    # Update layer parameters (placeholders from template)
    content = content.replace("BASE_FIRSTLAYER", f"{h1:.8f}")
    content = content.replace("BASE_NLAYERS", str(layers))
    content = content.replace("BASE_EXPANSION_RATIO", f"{growth}")

    with open(dict_path, 'w') as f:
        f.write(content)

    # Fix controlDict: writeInterval must be >= 1 for snappyHexMesh
    control_dict_path = os.path.join(case_dir, "system", "controlDict")
    with open(control_dict_path, 'r') as f:
        cd_content = f.read()
    cd_content = cd_content.replace("writeControl    timeStep;", "writeControl    adjustableRunTime;")
    cd_content = cd_content.replace("writeInterval   0;", "writeInterval   1;")
    with open(control_dict_path, 'w') as f:
        f.write(cd_content)

    return case_dir, stl_dir


def export_surface_stl(mesh, group_name, stl_path):
    """Export surface mesh group faces as STL for snappyHexMesh (port from tip-refine-snappy skill)."""
    if os.path.exists(stl_path):
        os.remove(stl_path)

    smesh_group = None
    for gr in mesh.GetGroups():
        if gr.GetName() == group_name:
            smesh_group = gr
            break

    if not smesh_group:
        raise Exception(f"Group '{group_name}' not found in mesh")

    face_ids = smesh_group.GetIDs()

    with open(stl_path, 'w') as f:
        f.write(f"solid {group_name}\n")
        for fid in face_ids:
            fnodes = mesh.GetElemNodes(fid)
            if len(fnodes) >= 3:
                pts = [mesh.GetNodeXYZ(ni) for ni in fnodes[:3]]
                v1 = (pts[1][0]-pts[0][0], pts[1][1]-pts[0][1], pts[1][2]-pts[0][2])
                v2 = (pts[2][0]-pts[0][0], pts[2][1]-pts[0][1], pts[2][2]-pts[0][2])
                normal = (
                    v1[1]*v2[2] - v1[2]*v2[1],
                    v1[2]*v2[0] - v1[0]*v2[2],
                    v1[0]*v2[1] - v1[1]*v2[0]
                )
                length = math.sqrt(normal[0]**2 + normal[1]**2 + normal[2]**2)
                if length > 0:
                    normal = (normal[0]/length, normal[1]/length, normal[2]/length)
                else:
                    normal = (0, 0, 1)
                f.write(f"  facet normal {normal[0]} {normal[1]} {normal[2]}\n")
                f.write("    outer loop\n")
                f.write(f"      vertex {pts[0][0]} {pts[0][1]} {pts[0][2]}\n")
                f.write(f"      vertex {pts[1][0]} {pts[1][1]} {pts[1][2]}\n")
                f.write(f"      vertex {pts[2][0]} {pts[2][1]} {pts[2][2]}\n")
                f.write("    endloop\n")
                f.write("  endfacet\n")
        f.write(f"endsolid {group_name}\n")


def run_snappy_hex_mesh(base_dir, base_name):
    """Run decomposePar + snappyHexMesh (parallel, detached) + reconstructParMesh + checkMesh.

    Ported from salome-tip-refine-snappy (proven working pattern):
    - bash -c 'source bashrc && cd case_dir && ...' (bashrc required, PATH alone insufficient)
    - decomposePar -force with tee log
    - mpirun --oversubscribe with auto-detected core count
    - reconstructParMesh -constant
    """
    import shutil
    import glob as glob_mod

    case_dir = os.path.join(base_dir, f"{base_name}-case")
    case_dir_abs = os.path.abspath(case_dir)

    print(f"\n[Running snappyHexMesh (parallel) - {base_name}]")

    # ---- Detect CPU cores (physical, no HyperThreading) ----
    cores_result = subprocess.run(
        "lscpu | grep '^Core(s) per socket:' | awk '{print $NF}' "
        "&& lscpu | grep '^Socket(s):' | awk '{print $NF}'",
        shell=True, capture_output=True, text=True
    )
    cores_per_socket = int(cores_result.stdout.strip().split('\n')[0].strip())
    sockets = int(cores_result.stdout.strip().split('\n')[1].strip())
    num_procs = cores_per_socket * sockets
    if num_procs < 2:
        num_procs = 2
    print(f"  > Auto-detected: {cores_per_socket} cores/socket x {sockets} sockets = {num_procs} procs")

    # ---- Create decomposeParDict ----
    decomp_dict = os.path.join(case_dir, "system", "decomposeParDict")
    with open(decomp_dict, 'w') as df:
        df.write("""FoamFile
{
    version     2.0;
    format      ascii;
    class       dictionary;
    object      decomposePar;
}

method        scotch;
numberOfSubdomains   %d;
coeffs
{
    n (%d 1 1);
}
""" % (num_procs, num_procs))
    print(f"  > decomposeParDict created: {num_procs} subdomains")

    # ---- Run decomposePar ----
    decomp_log = os.path.join(case_dir, "log.decomposePar")
    decomp_cmd = (
        f"bash -c 'source /opt/OpenFOAM/OpenFOAM-v2512/etc/bashrc 2>/dev/null && "
        f"cd {case_dir_abs} && decomposePar -force 2>&1 | tee {decomp_log}'"
    )
    ret = os.system(decomp_cmd)
    if ret != 0:
        print(f"  ERROR: decomposePar failed (exit {ret})")
        print(f"  Log: {decomp_log}")
        return False
    print(f"  > decomposePar completed successfully")

    # ---- Run snappyHexMesh in parallel via mpirun — setsid+nohup detach ----
    log_sh = os.path.join(case_dir, "log.snappyHexMesh")
    mpirun_cmd = (
        f"bash -c 'source /opt/OpenFOAM/OpenFOAM-v2512/etc/bashrc 2>/dev/null && "
        f"cd {case_dir_abs} && "
        f"setsid nohup mpirun --oversubscribe -np {num_procs} snappyHexMesh -parallel "
        f"> {log_sh} 2>&1'"
    )
    print(f"  Running: mpirun --oversubscribe -np {num_procs} snappyHexMesh -parallel (detached)")
    proc = subprocess.Popen(mpirun_cmd, shell=True, start_new_session=True)
    last_poll = time.time()
    while proc.poll() is None:
        time.sleep(1)
        if time.time() - last_poll >= 300:
            try:
                with open(log_sh, 'r') as f:
                    lines = f.readlines()
                print(f"  [snappyHexMesh] Running... (last 3 lines)\n" + '\n'.join(lines[-3:]))
            except (FileNotFoundError, IOError):
                print(f"  [snappyHexMesh] Running...")
            last_poll = time.time()
    ret = proc.returncode
    if ret != 0:
        print(f"\n  ERROR: snappyHexMesh failed (exit {ret})")
        print(f"  Log: {log_sh}")
        return False
    else:
        print(f"  > snappyHexMesh completed successfully")

    # ---- Run reconstructParMesh ----
    log_recon = os.path.join(case_dir, "log.reconstructParMesh")
    recon_cmd = (
        f"bash -c 'source /opt/OpenFOAM/OpenFOAM-v2512/etc/bashrc 2>/dev/null && "
        f"cd {case_dir_abs} && reconstructParMesh -constant 2>&1 | tee {log_recon}'"
    )
    ret = os.system(recon_cmd)
    if ret != 0:
        print(f"  ERROR: reconstructParMesh failed (exit {ret})")
        print(f"  Log: {log_recon}")
        return False
    print(f"  > reconstructParMesh completed successfully")

    # ---- Remove processor directories ----
    proc_dirs = glob_mod.glob(os.path.join(case_dir, "processor*"))
    for pd in proc_dirs:
        shutil.rmtree(pd)
    print(f"  > Removed {len(proc_dirs)} processor directories")

    # ---- checkMesh (final, after BL addition) ----
    checklog_path = os.path.join(case_dir, "checkMesh.log")
    check_cmd = (
        f"bash -c 'source /opt/OpenFOAM/OpenFOAM-v2512/etc/bashrc 2>/dev/null && "
        f"cd {case_dir_abs} && checkMesh 2>&1 | tee {checklog_path}'"
    )
    ret = os.system(check_cmd)
    if ret == 0:
        print(f"  > checkMesh completed (log: {checklog_path})")
    else:
        print(f"  > checkMesh exited with code {ret}")

    return True


