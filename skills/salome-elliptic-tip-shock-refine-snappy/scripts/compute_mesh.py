def run_compute_mesh():
    # 1. Parse Arguments (JSON file)
    args_file = None
    for arg in sys.argv:
        if arg.endswith('.json'):
            if ':' in arg:
                directory, filename = arg.split(':', 1)
                args_file = os.path.join(directory, filename)
            else:
                args_file = os.path.abspath(arg)
            break

    if not args_file or not os.path.exists(args_file):
        print("ERROR: Args file not found.")
        print("Usage: compute_mesh.py <directory>:<args_file.json>")
        return

    with open(args_file, 'r') as f:
        args = json.load(f)

    step_path = args['step_path']
    base_dir = args['base_dir']
    base_name = args['base_name']
    xl = args['xl']
    yl = args['yl']
    zl = args['zl']
    h1 = args['h1']
    layers = args['layers']
    growth = args['growth']
    fineness = args['fineness']
    T = args['T']
    min_size = args['min_size']
    surf_size = args['surf_size']
    max_size = args['max_size']
    cube_dx = args['cube_dx']
    cube_dy = args['cube_dy']
    cube_dz = args['cube_dz']

    # Refine Box params
    refine_dx = args.get('refine_dx', 0.5 * cube_dx)
    refine_dy = args.get('refine_dy', 2 * yl)
    refine_dz = args.get('refine_dz', 2 * zl)
    refine_cx = args.get('refine_cx', 0)
    refine_cy = args.get('refine_cy', 0)
    refine_cz = args.get('refine_cz', 0)
    refine_tx = args.get('refine_tx', 0)
    refine_ty = args.get('refine_ty', 0)
    refine_tz = args.get('refine_tz', 0)

    # refine_local_size from JSON (Step 4: max_size / 4)
    refine_local_size = args.get('refine_local_size', None)

    # Tip Wake params (optional)
    tip_csv_path = args.get('tip_csv_path', None)
    tip_points_count = args.get('tip_points_count', 0)
    tip_wake_lines = args.get('tip_wake_lines', [])
    tip_wake_refine_size = args.get('tip_wake_refine_size', None)

    # Shock Refine params (optional)
    shock_csv_path = args.get('shock_csv_path', None)
    shock_points_count = args.get('shock_points_count', 0)
    shock_refine_size = args.get('shock_refine_size', surf_size * 2)  # shock_refine_size = surf_size × 2

    # Refine Ellipsoid option (default: OFF)
    use_refine_ellipsoid = args.get('use_refine_ellipsoid', False)

    setup_hdf = os.path.join(base_dir, f"{base_name}_mesh_setup.hdf")
    mesh_hdf = os.path.join(base_dir, f"{base_name}_mesh.hdf")
    case_dir = os.path.join(base_dir, f"{base_name}-case")

    # 2. Show Parameters
    print("\n" + "="*60)
    print(f"STAGE 2: MESH COMPUTATION (with viscous layers) - {base_name}")
    print("="*60)

    print(f"\n[Mesh Parameters - User Input]")
    user_headers = ["Parameter", "Value", "Description"]
    user_rows = [
        ["h1", f"{h1:.6f} m", "First cell height (BL, for snappyHexMesh)"],
        ["layers", layers, "Boundary layer count (for snappyHexMesh)"],
        ["growth", f"{growth:.4f}", "BL growth rate (for snappyHexMesh)"],
        ["fineness", "Custom", "Custom mesh quality (growth_rate=0.3, segs/edge=1, segs/radius=3)"]
    ]
    print(format_table(user_headers, user_rows))

    # BL thickness calculation (display only)
    T = h1 * (math.pow(growth, layers) - 1) / (growth - 1)

    print(f"\n[Boundary Layer Thickness (calculated, display only)]")
    bl_headers = ["Parameter", "Value", "Formula"]
    bl_rows = [
        ["h1", f"{h1:.6f} m", "First layer height"],
        ["layers", layers, "Number of layers"],
        ["growth", f"{growth:.4f}", "Growth rate"],
        ["T (total)", f"{T:.6f} m", "h1*(growth^layers-1)/(growth-1)"],
    ]
    print(format_table(bl_headers, bl_rows))

    print(f"\n[Mesh Parameters - Derived]")
    derived_headers = ["Parameter", "Value", "Description"]
    derived_rows = [
        ["max_size", f"{max_size:.6f} m", "max(cube_dx,cube_dy,cube_dz)/50 (far-field coarsest)"],
        ["surf_size", f"{surf_size:.6f} m", "4 × T (surface cell size)"],
        ["min_size", f"{min_size:.6f} m", "2 × T (BL-based)"],
        ["refine_local_size", f"{refine_local_size:.6f} m", "max_size / 4 (refine box local size)"],
        ["refineBox_dim", f"{refine_dx:.4f} x {refine_dy:.4f} x {refine_dz:.4f}", "RefineBox dimensions (m)"],
        ["refineBox_center", f"({refine_cx:.2f}, {refine_cy:.2f}, {refine_cz:.2f})", "RefineBox center (m)"],
    ]
    if tip_wake_lines:
        derived_rows.append(["tip_wake_lines", len(tip_wake_lines), "Lines from tips to wake"])
        derived_rows.append(["tip_refine_size", f"{tip_wake_refine_size:.6f} m", "Wake line local size (Step 5: surf_size * 2)"])
    if shock_points_count > 0:
        derived_rows.append(["shock_points", shock_points_count, "Shock points (vertex refine)"])
        derived_rows.append(["shock_refine_size", f"{shock_refine_size:.6f} m", "Vertex local size (surf_size × 2)"])
    print(format_table(derived_headers, derived_rows))

    print(f"\n[Refine Box (wake capture)]")
    print(f"  Size: {refine_dx:.4f} x {refine_dy:.4f} x {refine_dz:.4f} m")
    print(f"  Center: ({refine_cx:.2f}, {refine_cy:.2f}, {refine_cz:.2f})")
    print(f"  Min corner: ({refine_tx:.2f}, {refine_ty:.2f}, {refine_tz:.2f})")
    print(f"  Netgen local size: {refine_local_size:.6f} m (= max_size / 4)")

    # 3. Rebuild Geometry (fresh from STEP)
    print("\n" + "-"*60)
    print("REBUILDING GEOMETRY FROM STEP FILE...")
    print("-"*60)

    imported_shape = geompy.ImportSTEP(step_path)
    geompy.addToStudy(imported_shape, "01_Imported_STEP")

    # Find the smallest face edge length from the STEP file
    # (used to validate min_size before meshing)
    all_shape_faces = geompy.SubShapeAll(imported_shape, geompy.ShapeType["FACE"])
    import math as _math
    smallest_edge = float('inf')
    for face in all_shape_faces:
        edges = geompy.SubShapeAll(face, geompy.ShapeType["EDGE"])
        for edge in edges:
            try:
                e_bb = geompy.BoundingBox(edge)
                e_len = _math.sqrt((e_bb[1]-e_bb[0])**2 + (e_bb[3]-e_bb[2])**2 + (e_bb[5]-e_bb[4])**2)
                if e_len < smallest_edge:
                    smallest_edge = e_len
            except RuntimeError:
                pass  # skip degenerate edge (void bounding box)
    print(f"  Smallest face edge length: {smallest_edge:.8f} m")

    x_min, x_max, y_min, y_max, z_min, z_max = geompy.BoundingBox(imported_shape)
    cx, cy, cz = (x_min + x_max) / 2, (y_min + y_max) / 2, (z_min + z_max) / 2

    try:
        tool_shape = geompy.MakeSolid([imported_shape])
        geompy.addToStudy(tool_shape, "02_Tool_Solid")
    except Exception:
        tool_shape = imported_shape

    # ===== Far-field Ellipsoid (was Box) =====
    # Ellipse face (x-y plane, center at origin)
    half_x = cube_dx / 2.0   # 5 * xl
    half_yz = max(cube_dy, cube_dz) / 2.0   # max(y, z) — symmetric in y & z

    e_origin = geompy.MakeVertex(0, 0, 0)
    e_axis = geompy.MakeVectorDXDYDZ(0, 0, 1)
    ellipse = geompy.MakeEllipse(e_origin, e_axis, half_x, half_yz, geompy.MakeVectorDXDYDZ(1, 0, 0))
    ellipse_face = geompy.MakeFaceWires([ellipse], 1)

    # Cutting half-space: x >= 0, covering full y extent
    cut_box = geompy.MakeFaceHW(cube_dx, 2.0 * half_yz, 1)
    geompy.TranslateDXDYDZ(cut_box, 0, -half_yz, 0)

    # Half-ellipse face (x >= 0)
    half_ellipse = geompy.MakeCutList(ellipse_face, [cut_box])

    # Revolution about OX axis → solid ellipsoid (semi-axes: x=half_x, y=z=half_yz)
    revolution_axis = geompy.MakeVectorDXDYDZ(1, 0, 0)
    farfield_ellipsoid = geompy.MakeRevolution(half_ellipse, revolution_axis, 360.0 * math.pi / 180.0)

    # Position: 0.25*(ellipsoid_xmax - ellipsoid_xmin) upstream of STEP center
    # 25% of ellipsoid length upstream, 75% downstream
    far_x_extent = 2.0 * half_x   # full x-length of ellipsoid
    far_x_offset = +0.25 * far_x_extent   # 25% upstream (left of center), 75% downstream
    farfield_ellipsoid = geompy.MakeTranslation(farfield_ellipsoid, cx + far_x_offset, cy, cz)
    geompy.addToStudy(farfield_ellipsoid, "04_Farfield_Ellipsoid")

    c_xmin, c_xmax, c_ymin, c_ymax, c_zmin, c_zmax = geompy.BoundingBox(farfield_ellipsoid)
    print(f"  Far-field Ellipsoid bbox: [{c_xmin:.4f}:{c_xmax:.4f}] "
          f"[{c_ymin:.4f}:{c_ymax:.4f}] [{c_zmin:.4f}:{c_zmax:.4f}]")

    try:
        domain = geompy.MakeCut(farfield_ellipsoid, tool_shape)
        op_type = "Cut"
    except Exception:
        domain = geompy.MakePartition([farfield_ellipsoid], [tool_shape])
        op_type = "Partition"

    geompy.addToStudy(domain, f"05_{base_name}_domain")

    # Reduce mesh complexity: use ComputeTolerance to merge close faces
    try:
        domain_clean = geompy.ComputeTolerance(domain, 0.001)
        geompy.addToStudy(domain_clean, f"05_{base_name}_domain_clean")
        domain = domain_clean
        geompy.Display(domain)
    except Exception:
        pass  # Keep original domain if ComputeTolerance fails

    # Adjust min_size if it's larger than the smallest face edge
    # (Netgen cannot mesh edges smaller than min_size)
    if smallest_edge > 0:
        if min_size > smallest_edge:
            old_min_size = min_size
            min_size = smallest_edge
            args['min_size'] = min_size
            print(f"  [min_size] Adjusted: {old_min_size:.6f} m → {min_size:.8f} m")
            print(f"    Reason: smallest face edge ({smallest_edge:.6f} m) < original min_size")
        else:
            print(f"  [min_size] OK: {min_size:.6f} m < smallest face edge ({smallest_edge:.6f} m)")

    # Identify far and model faces
    all_faces = geompy.SubShapeAll(domain, geompy.ShapeType["FACE"])
    tol = 1e-4
    far_faces, model_faces = [], []

    for face in all_faces:
        fb = geompy.BoundingBox(face)
        is_far = any(abs(fb[i] - [c_xmin, c_xmax, c_ymin, c_ymax, c_zmin, c_zmax][i]) < tol for i in range(6))
        if is_far: far_faces.append(face)
        else: model_faces.append(face)

    group_far = geompy.CreateGroup(domain, geompy.ShapeType["FACE"])
    geompy.UnionList(group_far, far_faces)
    geompy.addToStudyInFather(domain, group_far, "far")

    group_model = geompy.CreateGroup(domain, geompy.ShapeType["FACE"])
    geompy.UnionList(group_model, model_faces)
    geompy.addToStudyInFather(domain, group_model, f"{base_name}_surface")

    print(f"  > Boolean Operation: {op_type} Completed")
    print(f"  > Far faces: {len(far_faces)}, Model faces: {len(model_faces)}")

    # 3b. Create Refine Ellipsoid (same revolution pattern as far-field) — only if option ON
    refine_box_volume_group = None
