    print("\n" + "="*60)
    print("STAGE 3: MESH SETUP & COMPUTATION (with viscous layers)")
    print("="*60)

    print("\n  Setting up mesh parameters...")
    mesh = smesh.Mesh(domain, f"{base_name}_mesh")
    netgen = mesh.Tetrahedron(algo=smeshBuilder.NETGEN_1D2D3D)

    params = netgen.Parameters()
    params.SetNbThreads(8)
    params.SetMaxSize(max_size)
    params.SetMinSize(min_size)
    params.SetLocalSizeOnShape(group_model, surf_size)
    params.SetUseSurfaceCurvature(1)
    # params.SetFineness(fineness)  # Use custom params (growth_rate=0.3, segs/edge=1, segs/radius=3)

    # Custom mesh quality params (commented out - use custom params directly):
    # params.SetFineness(fineness)  # deleted - use custom params directly
    params.SetGrowthRate(0.3)
    params.SetNbSegPerEdge(1)
    params.SetNbSegPerRadius(3)
    # Custom mesh quality params (disabled):
    # params.SetNbSurfOptSteps(3)        # Surface mesh optimization → skewness ↓
    # params.SetNbVolOptSteps(0)         # Volume optimization
    params.SetOptimize(1)              # 3D tet optimization (ENABLED)
    # params.SetSecondOrder(0)           # Linear elements (OpenFOAM compat)

    print("  > Mesh quality: Custom (growth_rate=0.3, segs/edge=1, segs/radius=3) + SetOptimize(1)")
    if refine_box_volume_group is not None:
        netgen.SetLocalSizeOnShape(refine_box_volume_group, refine_local_size)

    print("  Defining mesh groups...")
    mesh.GroupOnGeom(group_far, 'far', SMESH.FACE)
    mesh.GroupOnGeom(group_model, f'{base_name}_surface', SMESH.FACE)

